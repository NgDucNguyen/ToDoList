/* Deterministic, dependency-free softmax training. No personal data or downloads. */
const fs = require('node:fs');
const path = require('node:path');
const { features, classify, normalize } = require('../chatbot-nlu');
const data = require('../chatbot-training.json');
const root = path.resolve(__dirname, '..'), labels = Object.keys(data.intents), featureCount = 4096;
const seen = new Set();
const rows = labels.flatMap((label, target) => data.intents[label].map(text => {
  const key = normalize(text);
  if (seen.has(key)) return null;
  seen.add(key); return { text, target, x: features(text, featureCount) };
}).filter(Boolean));
for (const [text] of data.evaluation) if (seen.has(normalize(text))) throw new Error('Evaluation overlaps training: ' + text);
const weights = labels.map(() => new Float64Array(featureCount)), bias = labels.map(() => 0);
let seed = 20261118;
const random = () => { seed ^= seed << 13; seed ^= seed >>> 17; seed ^= seed << 5; return (seed >>> 0) / 4294967296; };
const order = rows.map((_, i) => i), counts = labels.map((_, c) => rows.filter(row => row.target === c).length);
for (let epoch = 0; epoch < 160; epoch++) {
  for (let i = order.length - 1; i > 0; i--) { const j = Math.floor(random() * (i + 1)); [order[i], order[j]] = [order[j], order[i]]; }
  const rate = .32 / (1 + epoch / 80);
  for (const index of order) {
    const row = rows[index], logits = labels.map((_, c) => row.x.reduce((sum, [i, value]) => sum + weights[c][i] * value, bias[c]));
    const max = Math.max(...logits), exps = logits.map(value => Math.exp(value - max)), total = exps.reduce((sum, v) => sum + v, 0);
    const balance = rows.length / (labels.length * counts[row.target]);
    for (let c = 0; c < labels.length; c++) {
      const error = (exps[c] / total - Number(c === row.target)) * balance;
      for (const [i, value] of row.x) weights[c][i] -= rate * (error * value + .0001 * weights[c][i]);
      bias[c] -= rate * error;
    }
  }
}
const model = { version: 1, algorithm: 'hashed word/character ngrams + supervised softmax regression', featureCount, labels, trainingExamples: rows.length, seed: 20261118,
  weights: weights.map(row => Array.from(row, value => Number(value.toFixed(6)))), bias: bias.map(value => Number(value.toFixed(6))) };
const predictions = data.evaluation.map(([text, expected]) => { const prediction = classify(text, model); return { text, expected, predicted: prediction.intent, confidence: Number(prediction.confidence.toFixed(3)), correct: expected === prediction.intent }; });
const correct = predictions.filter(row => row.correct).length;
const report = { trainingExamples: rows.length, evaluationExamples: predictions.length, correct, accuracy: Number((correct / predictions.length).toFixed(4)), note: 'Fixed held-out examples, not a guarantee for arbitrary Vietnamese. Calendar/date/action tests are separate.', failures: predictions.filter(row => !row.correct), predictions };
model.evaluation = { correct, total: predictions.length, accuracy: report.accuracy };
fs.writeFileSync(path.join(root, 'chatbot-model.js'), '/* Generated by npm run train:chatbot. Do not edit weights manually. */\n(function(root){const model=' + JSON.stringify(model) + ';root.PlannerChatbotModel=model;if(typeof module===\'object\'&&module.exports)module.exports=model;})(typeof globalThis!==\'undefined\'?globalThis:this);\n');
fs.writeFileSync(path.join(root, 'chatbot-training-report.json'), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify({ trainingExamples: rows.length, intents: labels.length, heldOut: predictions.length, correct, accuracy: report.accuracy, failures: report.failures }, null, 2));
if (report.accuracy < .85) process.exitCode = 1;
